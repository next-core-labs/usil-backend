export function normalizeSeoPath(pathname: string): string {
  const path = String(pathname || '').split('?')[0].split('#')[0];
  const trimmed = path.replace(/\/+$/, '');
  return trimmed || '/';
}

export function seoMetaForPath(pathname: string): SeoMetaEntry | null {
  return SEO_META_PAGES[normalizeSeoPath(pathname)] || null;
}

